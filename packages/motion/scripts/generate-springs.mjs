import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = JSON.parse(readFileSync(new URL('./spring-source.json', import.meta.url), 'utf8'));
function generate([dampingRatio, stiffness, fallbackDuration, fallbackEasing]) {
  const omega = Math.sqrt(stiffness);
  const damped = Math.sqrt(1 - dampingRatio ** 2);
  const value = ms => {
    const t = ms / 1000;
    return dampingRatio === 1
      ? 1 - (1 + omega * t) * Math.exp(-omega * t)
      : 1 - Math.exp(-dampingRatio * omega * t) * (Math.cos(omega * damped * t) + dampingRatio / damped * Math.sin(omega * damped * t));
  };
  // Scan through a conservative envelope bound and retain the last millisecond
  // outside the 0.1% band (the convention used in S1).
  let bound = 0;
  while (dampingRatio === 1
    ? (1 + omega * bound / 1000) * Math.exp(-omega * bound / 1000) > 0.001
    : Math.exp(-dampingRatio * omega * bound / 1000) / damped > 0.001) bound++;
  let duration = 0;
  for (let ms = 0; ms <= bound; ms++) if (Math.abs(1 - value(ms)) > 0.001) duration = ms + 1;
  const stopValue = ms => ms === duration ? 1 : value(ms);
  const stops = [0, duration];
  while (stops.length < 26) {
    let error = -1, point = 0;
    for (let j = 0; j < stops.length - 1; j++) {
      const a = stops[j], b = stops[j + 1], va = stopValue(a), vb = stopValue(b);
      for (let i = 1; i < 100; i++) {
        const ms = a + (b - a) * i / 100;
        const delta = Math.abs(value(ms) - (va + (vb - va) * i / 100));
        if (delta > error) { error = delta; point = ms; }
      }
    }
    stops.push(point);
    stops.sort((a, b) => a - b);
  }
  // Offset interior samples slightly toward the curve's chord error, reducing
  // the maximum error without changing either endpoint.
  const adjusted = stops.map((ms, i) => {
    if (i === 0 || i === stops.length - 1) return stopValue(ms);
    const a = stops[i - 1], b = stops[i + 1];
    const chord = stopValue(a) + (stopValue(b) - stopValue(a)) * (ms - a) / (b - a);
    return value(ms) - Math.sign(chord - value(ms)) * 0.0004;
  });
  const easing = `linear(${stops.map((ms, i) => `${Number(adjusted[i].toFixed(6))} ${Number((ms / duration * 100).toFixed(4))}%`).join(', ')})`;
  return { dampingRatio, stiffness, fallback: { duration: fallbackDuration, easing: fallbackEasing }, linear: { duration, easing } };
}
const generated = Object.fromEntries(Object.entries(source).map(([key, tuples]) => [key, tuples.map(generate)]));
const output = `// Generated by scripts/generate-springs.mjs; do not edit.\nexport const springData = ${JSON.stringify(generated, null, 2)} as const;\n`;
const target = fileURLToPath(new URL('../src/spring-data.generated.ts', import.meta.url));
const cssTarget = fileURLToPath(new URL('../public/motion-springs.generated.css', import.meta.url));
const start = '/* BEGIN GENERATED SPRING TOKENS */';
const end = '/* END GENERATED SPRING TOKENS */';
const declarations = (scheme, variant, indent = '  ') => ['fast', 'default', 'slow'].flatMap((speed, index) =>
  ['spatial', 'effects'].flatMap(kind => {
    const pair = generated[kind === 'effects' ? 'effects' : scheme][index][variant];
    const prefix = `--udx-motion-spring-${speed}-${kind}`;
    return [`${indent}${prefix}-duration: ${pair.duration}ms;`, `${indent}${prefix}-easing: ${pair.easing};`];
  })).join('\n');
const block = `${start}
/* Generated by scripts/generate-springs.mjs; do not edit. */
:root {
${declarations('expressive', 'fallback')}
}

:root[data-motion-scheme='standard'] {
${declarations('standard', 'fallback')}
}

@supports (animation-timing-function: linear(0, 1)) {
  :root {
${declarations('expressive', 'linear', '    ')}
  }

  :root[data-motion-scheme='standard'] {
${declarations('standard', 'linear', '    ')}
  }
}
${end}`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) { console.error('Generated spring data is stale'); process.exitCode = 1; }
  if (readFileSync(cssTarget, 'utf8') !== `${block}\n`) { console.error('Generated spring CSS is stale'); process.exitCode = 1; }
} else {
  writeFileSync(target, output);
  writeFileSync(cssTarget, `${block}\n`);
}
